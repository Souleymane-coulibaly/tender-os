const SERVER_ERROR_MESSAGE = "Une erreur serveur est survenue. Veuillez réessayer.";

type ApiErrorLike = { status: number; code: string };

/** Reconnaît les erreurs des deux clients API (`AppApiError`, `PlatformApiError`) par leur forme. */
function isApiErrorLike(error: unknown): error is ApiErrorLike {
  return (
    typeof error === "object" &&
    error !== null &&
    typeof (error as Partial<ApiErrorLike>).code === "string" &&
    typeof (error as Partial<ApiErrorLike>).status === "number"
  );
}

/**
 * Message français précis pour une erreur API dont le code est connu, sinon `undefined` : l'appelant
 * garde alors son propre repli, souvent plus juste pour son contexte qu'un message générique.
 */
export function apiErrorMessage(error: unknown): string | undefined {
  return isApiErrorLike(error) ? API_ERROR_MESSAGES[error.code] : undefined;
}

/**
 * Toujours un message français : celui du code s'il est connu, puis celui du statut HTTP, puis
 * `fallback`. Jamais le message brut de l'API.
 */
export function describeApiError(error: unknown, fallback = "Une erreur est survenue."): string {
  if (!isApiErrorLike(error)) return fallback;
  return (
    API_ERROR_MESSAGES[error.code] ??
    STATUS_MESSAGES[error.status] ??
    (error.status >= 500 ? SERVER_ERROR_MESSAGE : fallback)
  );
}
